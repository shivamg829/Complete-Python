# Arithamatic Operators
a = 10
b = 3
print("Addition:", a + b) # Addition
print("Subtraction:", a - b) # Subtraction
print("Multiplication:", a * b) # Multiplication
print("Division:", a / b) # Division
print("Floor Division:", a // b) # Floor Division
print("Modulus:", a % b) # Modulus

# Comparison Operators
x = 5
y = 10
print("Equal to:", x == y) # Equal to
print("Not equal to:", x != y) # Not equal to
print("Greater than:", x > y) # Greater than
print("Less than:", x < y) # Less than
print("Greater than or equal to:", x >= y) # Greater than or equal to
print("Less than or equal to:", x <= y) # Less than or equal to

# Logical Operators
p = True
q = False
print("Logical AND:", p and q) # Logical AND
print("Logical OR:", p or q) # Logical OR
print("Logical NOT:", not p) # Logical NOT

# Bitwise Operators
m = 5  # Binary: 0101
n = 3  # Binary: 0011
print("Bitwise AND:", m & n) # Bitwise AND
print("Bitwise OR:", m | n) # Bitwise OR
print("Bitwise XOR:", m ^ n) # Bitwise XOR
print("Bitwise NOT:", ~m) # Bitwise NOT
print("Left Shift:", m << 1) # Left Shift
print("Right Shift:", m >> 1) # Right Shift

# Assignment Operators
num = 10
num += 5  # Equivalent to num = num + 5
print("After += 5:", num)
num -= 3  # Equivalent to num = num - 3
print("After -= 3:", num)
num *= 2  # Equivalent to num = num * 2
print("After *= 2:", num)
num /= 4  # Equivalent to num = num / 4
print("After /= 4:", num)

# Membership Operators
list1 = [1, 2, 3, 4, 5]
print("Is 3 in list1?", 3 in list1) # Membership Operator:
print("Is 6 not in list1?", 6 not in list1) # Membership

# Identity Operators
a = 10
b = 10
print("Is a identical to b?", a is b) # Identity Operator: is
print("Is a not identical to b?", a is not b) # Identity Operator: is
